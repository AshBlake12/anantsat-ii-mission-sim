class Igrf {
public:
    static constexpr int NMAX = 13;
    static constexpr double A_REF = 6371.2;  // km, IGRF reference radius

    explicit Igrf(double decimal_year, int nmax = NMAX) : nmax_(std::min(nmax, NMAX)) {
        double dy = decimal_year - 2025.0;
        for (auto& c : IGRF14) {
            g_[c.n][c.m] = c.g + c.gd * dy;
            h_[c.n][c.m] = c.h + c.hd * dy;
        }
    }

    // Magnetic field (tesla, ECEF) at an ECEF position (km).
    Vec3 field_ecef(const Vec3& r_ecef) const {
        const double r = norm(r_ecef);
        const double ct = r_ecef.z / r;
        double st = std::sqrt(std::max(0.0, 1.0 - ct * ct));
        st = std::max(st, 1e-10);
        const double ph = std::atan2(r_ecef.y, r_ecef.x);

        double P[NMAX + 1][NMAX + 1] = {}, dP[NMAX + 1][NMAX + 1] = {};
        P[0][0] = 1.0;
        for (int n = 1; n <= nmax_; ++n) {
            for (int m = 0; m <= n; ++m) {
                if (n == m) {
                    if (n == 1) { P[1][1] = st; dP[1][1] = ct; }
                    else {
                        double k = std::sqrt((2.0 * n - 1.0) / (2.0 * n));
                        P[n][n] = k * st * P[n - 1][n - 1];
                        dP[n][n] = k * (st * dP[n - 1][n - 1] + ct * P[n - 1][n - 1]);
                    }
                } else {
                    double a = std::sqrt(double(n * n - m * m));
                    double b = n - 2 >= m ? std::sqrt(double((n - 1) * (n - 1) - m * m)) : 0.0;
                    double p2 = n - 2 >= m ? P[n - 2][m] : 0.0, dp2 = n - 2 >= m ? dP[n - 2][m] : 0.0;
                    P[n][m] = ((2.0 * n - 1.0) * ct * P[n - 1][m] - b * p2) / a;
                    dP[n][m] = ((2.0 * n - 1.0) * (ct * dP[n - 1][m] - st * P[n - 1][m]) - b * dp2) / a;
                }
            }
        }
        double br = 0, bt = 0, bp = 0;
        const double ar = A_REF / r;
        double arn = ar * ar;  // (a/r)^(n+2) starts at n=0 -> ar^2
        for (int n = 1; n <= nmax_; ++n) {
            arn *= ar;
            for (int m = 0; m <= n; ++m) {
                double cm = std::cos(m * ph), sm = std::sin(m * ph);
                double gh = g_[n][m] * cm + h_[n][m] * sm;
                br += (n + 1) * arn * gh * P[n][m];
                bt -= arn * gh * dP[n][m];
                bp -= arn * m * (-g_[n][m] * sm + h_[n][m] * cm) * P[n][m] / st;
            }
        }
        const double cp = std::cos(ph), sp = std::sin(ph);
        Vec3 er{st * cp, st * sp, ct}, et{ct * cp, ct * sp, -st}, ep{-sp, cp, 0};
        return (er * br + et * bt + ep * bp) * 1e-9;
    }

    // Unit vector of the centred-dipole axis (points to the geomagnetic north pole's antipode
    // convention-free: returned as the direction of the dipole moment, ECEF).
    Vec3 dipole_axis_ecef() const { return unit(Vec3{g_[1][1], h_[1][1], g_[1][0]}); }

private:
    int nmax_;
    double g_[NMAX + 1][NMAX + 1] = {}, h_[NMAX + 1][NMAX + 1] = {};
};

